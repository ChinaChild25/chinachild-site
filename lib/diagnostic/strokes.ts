/**
 * Минимальные пути черт для нескольких ключевых иероглифов.
 *
 * Каждый stroke — массив SVG-path "M ... C ... " в координатах viewBox 100×100.
 * Это не каллиграфический шрифт — это упрощённый «логотип» иероглифа,
 * достаточный, чтобы:
 *   1) на лендинге красиво «отрисовываться» порядком черт;
 *   2) в типе F показывать порядок (правильный или нарочно неправильный).
 *
 * Расчёт totalLength делается в браузере через `getTotalLength()`.
 */

export type StrokePath = string;

export interface StrokeChar {
  hanzi: string;
  viewBox: string; // "0 0 100 100"
  strokes: StrokePath[];
}

export const STROKE_CHARS: Record<string, StrokeChar> = {
  // 你 — основной иероглиф лендинга. Упрощённая 7-чёрточная форма.
  你: {
    hanzi: "你",
    viewBox: "0 0 100 100",
    strokes: [
      // 1. наклонная влево
      "M 22 22 L 12 80",
      // 2. вертикаль
      "M 30 30 L 30 88",
      // 3. горизонталь верхняя
      "M 42 30 L 88 30",
      // 4. наклонная влево внутри
      "M 60 38 L 50 60",
      // 5. наклонная вправо внутри
      "M 60 38 L 75 60",
      // 6. вертикаль внизу
      "M 62 60 L 62 86",
      // 7. горизонталь внизу
      "M 50 78 L 80 78",
    ],
  },
  // 口 — простой 3-чёрточный, для типа F
  口: {
    hanzi: "口",
    viewBox: "0 0 100 100",
    strokes: [
      "M 25 25 L 25 80",
      "M 25 25 L 78 25",
      "M 78 25 L 78 80 L 22 80",
    ],
  },
  // 人 — 2 черты
  人: {
    hanzi: "人",
    viewBox: "0 0 100 100",
    strokes: ["M 50 18 L 18 88", "M 52 36 L 84 88"],
  },
  // 中 — 4 черты
  中: {
    hanzi: "中",
    viewBox: "0 0 100 100",
    strokes: [
      "M 30 28 L 70 28",
      "M 30 28 L 30 70",
      "M 30 70 L 70 70 L 70 28",
      "M 50 12 L 50 92",
    ],
  },
  // 好 — 6 черт
  好: {
    hanzi: "好",
    viewBox: "0 0 100 100",
    strokes: [
      "M 18 24 L 38 24",
      "M 30 16 L 30 70",
      "M 18 50 L 38 50 L 38 80 L 24 92",
      "M 60 12 L 60 92",
      "M 50 28 L 88 28",
      "M 60 56 L 88 56",
    ],
  },
  // 学 — упрощённо 5 черт
  学: {
    hanzi: "学",
    viewBox: "0 0 100 100",
    strokes: [
      "M 36 12 L 30 26",
      "M 64 12 L 70 26",
      "M 18 32 L 82 32",
      "M 28 46 L 72 46",
      "M 50 46 L 50 90 L 32 90",
    ],
  },
};

/** Если для иероглифа нет данных — отдаём первый stroke-char как fallback. */
export function getStrokeChar(hanzi: string): StrokeChar | null {
  return STROKE_CHARS[hanzi] ?? null;
}

/** Для типа F: вернуть переставленный порядок (с гарантией: первая черта НЕ первая). */
export function shuffleStrokes(strokes: StrokePath[]): StrokePath[] {
  if (strokes.length < 2) return strokes;
  // Сдвиг циклом на 1 — детерминированно «неправильный» порядок без рандома
  // (рандом ломал бы воспроизводимость теста).
  return [...strokes.slice(1), strokes[0]];
}
