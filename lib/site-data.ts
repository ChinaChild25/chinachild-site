export type AudienceSegment = {
  title: string;
  href: string;
  audience: string;
  badge: string;
  description: string;
  outcomes: string[];
  accent: "violet" | "cream" | "lime" | "sky";
};

export type Course = {
  slug: string;
  title: string;
  href: string;
  level: string;
  duration: string;
  format: string;
  price: string;
  priceValue?: string;
  description: string;
  audience: string;
  outcome: string;
  /** Skills/topics taught — surfaces in Google Course Carousel */
  teaches?: string[];
  /** Required prior knowledge */
  prerequisites?: string;
  /** Credential awarded after completion */
  credentialAwarded?: string;
  /** ISO 8601 duration (e.g. "PT80H" for 80 lessons of 1h) */
  timeRequiredIso?: string;
  /** Slug of the lead instructor (resolves to teacher Person via @id) */
  instructorSlug?: string;
};

export type Teacher = {
  slug: string;
  name: string;
  specialization: string;
  experience: string;
  credentials: string;
  image: string;
  /** Long-form bio shown on the dedicated /team/[slug] page */
  bio?: string;
  /** Topics the teacher is an authority on — fed into Person.knowsAbout */
  knowsAbout?: string[];
  /** External profile URLs — fed into Person.sameAs (E-E-A-T signal) */
  sameAs?: string[];
  /** Job title/role for Person.jobTitle */
  jobTitle?: string;
  /** Education entry, fed into Person.alumniOf */
  alumniOf?: string;
};

