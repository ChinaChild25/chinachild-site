export type TeacherCertificate = {
  /** Путь в /public, например /team/certificates/zhao-li-hsk-6.webp */
  src: string;
  /** Краткое название для schema.org (HSK 6, диплом бакалавра…) */
  name: string;
  alt: string;
  caption?: string;
  title?: string;
  width?: number;
  height?: number;
};

export type Teacher = {
  slug: string;
  name: string;
  displayName?: string;
  location?: string;
  subject?: string;
  /** Имя в дательном падеже («Записаться к …»). Без этого поля
   *  теряются окончания: «к Милена» вместо «к Милене». */
  firstNameDative: string;
  specialization: string;
  experience: string;
  credentials: string;
  image: string;
  /** Длинный alt — для SEO/E-E-A-T и доступности (рендерится в <img alt>). */
  imageAlt?: string;
  /** Tooltip — короткий title по hover. */
  imageTitle?: string;
  /** Long-form bio shown on the dedicated /team/[slug] page */
  bio?: string;
  profileArticle?: string[];
  worksWith?: string[];
  educationTimeline?: string[];
  /** Сканы дипломов и сертификатов — файлы в /public/team/certificates/ */
  certificates?: TeacherCertificate[];
  /** Topics the teacher is an authority on — fed into Person.knowsAbout */
  knowsAbout?: string[];
  /** External profile URLs — fed into Person.sameAs (E-E-A-T signal) */
  sameAs?: string[];
  /** Job title/role for Person.jobTitle */
  jobTitle?: string;
  /** Education entry, fed into Person.alumniOf */
  alumniOf?: string;
};

