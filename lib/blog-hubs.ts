const HUB_BY_SLUG = new Map(BLOG_HUBS.map((h) => [h.slug, h]));
const HUB_BY_CATEGORY = new Map(BLOG_HUBS.map((h) => [h.category, h]));

export function getHubBySlug(slug: string): BlogHub | undefined {
  return HUB_BY_SLUG.get(slug);
}

export function getHubByCategory(category: string): BlogHub | undefined {
  return HUB_BY_CATEGORY.get(category);
}
