/**
 * HowTo schema overlays for step-format blog posts.
 *
 * Mapping is opt-in per slug — we only emit HowTo JSON-LD when a post follows
 * a genuine step-by-step structure (e.g. "День 1", "Неделя 1–2"). Wiring this
 * through frontmatter would require nested-array support in the flat parser
 * in lib/blog.ts; a separate config file keeps the parser simple and the
 * SEO surface explicit.
 *
 * Each step text mirrors the H2 in the article so Google can map the SERP
 * HowTo widget to the visible content.
 */

